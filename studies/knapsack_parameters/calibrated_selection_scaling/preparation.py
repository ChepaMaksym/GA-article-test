"""Pinned inputs, exhaustive freshness audit, exact references and shared banks.

No search or numerical preparation is permitted outside the enclosed CI phase.
The bank recipe is empty first, followed by nineteen independent PCG64 integer
bit vectors, entropy [preparation_seed, task_index, search_seed, 1]. Every profile
uses the same prefix and the same six untouched operator states, generated by
create_random_generators(search_seed, task_index, 0). OPT stays in certificates.
"""
