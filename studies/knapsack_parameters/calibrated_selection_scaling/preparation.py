BANK_SCHEMA = "calibrated-selection-shared-bank-v1"
EXACT_SHA256 = "dd74a93ba074518fa66e8fbf64debcc67c54c12aa55c12bc4afda51e2be657ce"
EXACT_PATH = REPOSITORY / "studies/knapsack_parameters/population_size_study/exact.py"
