def _canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False, allow_nan=False).encode("utf-8")


def _sha(raw):
    return hashlib.sha256(raw).hexdigest()


def identity(path):
    raw = Path(path).read_bytes()
    return {"bytes": len(raw), "sha256": _sha(raw)}


def _descriptor(root, path):
    return {"path": Path(path).relative_to(root).as_posix(), **identity(path)}


def _safe(root, relative, *, exists=True):
    require(type(relative) is str and relative and "\\" not in relative and ":" not in relative,
            "Unsafe input-relative path")
    pure = PurePosixPath(relative)
    require(not pure.is_absolute() and all(part not in ("", ".", "..") for part in pure.parts),
            "Unsafe input-relative path")
    base = Path(root).resolve()
    path = base.joinpath(*pure.parts)
    require(path.resolve().is_relative_to(base), "Input path escapes its root")
    cursor = path
    while cursor != base:
        require(not cursor.is_symlink(), "Symbolic-link input members are refused")
        cursor = cursor.parent
    require(not exists or path.is_file(), "Required input is absent: " + relative)
    return path


def validate_problem(problem):
    require(type(problem) is dict and set(problem) == {"n", "capacity", "weights", "profits"},
            "Only four search problem fields are accepted")
    require(type(problem["n"]) is int and problem["n"] >= 2 and
            type(problem["capacity"]) is int and problem["capacity"] > 0, "Invalid problem dimension/capacity")
    for field in ("weights", "profits"):
        require(type(problem[field]) is list and len(problem[field]) == problem["n"] and
                all(type(value) is int and value > 0 for value in problem[field]), "Invalid item vector")


def parse_kp_bytes(raw, n):
    """Preserve source item order and reject extra columns, rows and signs."""
    require(type(raw) is bytes and type(n) is int and n >= 2, "Invalid source parse request")
    rows = [line.split() for line in raw.decode("utf-8", errors="strict").splitlines() if line.strip()]
    require(len(rows) == n + 2 and len(rows[0]) == len(rows[1]) == 1,
            "Unexpected KPLIB dimension/capacity rows")
    require(all(len(row) == 2 for row in rows[2:]) and
            all(re.fullmatch(r"[0-9]+", token) for row in rows for token in row), "Malformed KPLIB item rows")
    problem = {"n": int(rows[0][0]), "capacity": int(rows[1][0]),
               "profits": [int(row[0]) for row in rows[2:]],
               "weights": [int(row[1]) for row in rows[2:]]}
    require(problem["n"] == n, "Unexpected KPLIB item count")
    validate_problem(problem)
    # Independent flattened-token reconstruction also detects accidental swaps.
    values = [int(token) for token in raw.decode("utf-8").split()]
    independent = {"n": values[0], "capacity": values[1],
                   "profits": values[2::2], "weights": values[3::2]}
    require(independent == problem, "Independent source parsers disagree")
    return problem


def problem_sha256(problem):
    validate_problem(problem)
    return _sha(_canonical(problem))


def unordered_problem_sha256(problem):
    validate_problem(problem)
    return _sha(_canonical({"n": problem["n"], "capacity": problem["capacity"],
                            "items": sorted(zip(problem["profits"], problem["weights"], strict=True))}))


def _source_bytes(row, source_root=None, *, deadline=None):
    _deadline(deadline)
    relative = row["source_path"]
    require(type(row.get("bytes")) is int and row["bytes"] > 0 and
            re.fullmatch(r"[0-9a-f]{40}", row.get("git_blob_sha1", "")), "Unpinned source identity")
    require(row.get("url", config.SOURCE_BASE + relative) == config.SOURCE_BASE + relative,
            "Source URL is not the immutable registered revision")
    if source_root is not None:
        raw = _safe(source_root, relative).read_bytes()
    else:
        request = urllib.request.Request(config.SOURCE_BASE + relative,
                                         headers={"User-Agent": "calibrated-selection-preparation"})
        timeout = 30 if deadline is None else max(0.1, min(30, deadline - monotonic()))
        with urllib.request.urlopen(request, timeout=timeout) as response:
            require(response.geturl() == config.SOURCE_BASE + relative, "Source fetch changed immutable URL")
            raw = response.read(row["bytes"] + 1)
    _deadline(deadline)
    git_blob = hashlib.sha1(b"blob " + str(len(raw)).encode("ascii") + b"\0" + raw).hexdigest()
    require(len(raw) == row["bytes"] and git_blob == row["git_blob_sha1"],
            "Input bytes differ from the pinned Git-tree entry")
    if row.get("source_sha256") is not None:
        require(_sha(raw) == row["source_sha256"], "Input SHA-256 differs from the source registry")
    return raw


def _source_registry(stage):
    path = ROOT / "data/source_registry.json"
    registry = read_json(path)
    require(registry.get("source_commit") == config.SOURCE_COMMIT and
            registry.get("repository") == "likr/kplib", "Wrong source registry revision/repository")
    records = registry.get("records", []) + registry.get("historical_records", [])
    require(type(records) is list, "Source registry records are absent")
    inventory = {row["source_path"]: row for row in records}
    require(len(inventory) == len(records), "Duplicate source-registry paths")
    selected = []
    tasks = config.task_descriptors(stage)
    if stage == "technical":
        tasks += config.task_descriptors("main")
    for task in tasks:
        require(task["source_path"] in inventory, "Registered task is absent from the pinned source inventory")
        row = inventory[task["source_path"]]
        require(all(row.get(key, value) == value for key, value in task.items()),
                "Source descriptor contradicts registered study identity")
        selected.append({**row, **task})
    return registry, selected, identity(path)


def _fingerprint(problem, label, source_sha256=None):
    return {"identity": label, "n": problem["n"], "source_sha256": source_sha256,
            "problem_sha256": problem_sha256(problem),
            "unordered_problem_sha256": unordered_problem_sha256(problem)}


def _retained_historical_inputs(roots):
    """Inspect input files only; search journals and outcome tables are excluded."""
    files, fingerprints, task_ids, rejected_dimensions = [], [], set(), 0

    def inspect(document, label):
        """Select input identities without consuming any score/outcome field."""
        if type(document) is list:
            for number, value in enumerate(document):
                inspect(value, f"{label}/{number}")
            return
        if type(document) is not dict:
            return
        problem = document.get("problem")
        if type(problem) is dict and set(problem) == {"n", "capacity", "weights", "profits"}:
            validate_problem(problem)
            if problem["n"] in (100, 500):
                fingerprints.append(_fingerprint(problem, label))
        n = document.get("n", problem.get("n") if type(problem) is dict else None)
        for key in ("task_id", "task"):
            value = document.get(key)
            if type(value) is str:
                if re.fullmatch(r"n00(?:100|500)-(?:UC|WC|SC)-s[0-9]{3}", value):
                    task_ids.add(value)
                elif n in (100, 500) and re.fullmatch(r"(?:UC|WC|SC)-s[0-9]{3}", value):
                    task_ids.add(f"n{n:05d}-{value}")
        for key in ("records", "cases", "case", "run", "runs", "log", "journal", "bank", "source", "sources",
                    "inputs", "tasks", "technical_cases", "main_cases", "historical_records", "selected", "archives"):
            if key in document:
                inspect(document[key], label + "/" + key)
    for supplied in roots:
        root = Path(supplied).resolve()
        require(root.is_dir() and not root.is_symlink(), "Historical input root is unavailable")
        # Raw KPLIB files are sufficient to fingerprint retained source order.
        # Older input registries may contain the four problem fields directly.
        candidates = set(root.rglob("*.kp"))
        candidates.update(root.rglob("*.json"))
        candidates.update(root.rglob("*.json.gz"))
        for path in sorted(candidates):
            frozen_history = (ROOT / "data/historical_evidence").resolve()
            if ROOT.resolve() in path.resolve().parents and not path.resolve().is_relative_to(frozen_history):
                continue
            require(not path.is_symlink() and path.resolve().is_relative_to(root), "Unsafe retained source member")
            descriptor = {"root": str(root), "path": path.relative_to(root).as_posix(), **identity(path)}
            files.append(descriptor)
            raw = path.read_bytes()
            if path.suffix == ".kp":
                first = raw.decode("utf-8").split()[0]
                require(first.isdecimal(), "Malformed retained KPLIB header")
                n = int(first)
                if n not in (100, 500):
                    rejected_dimensions += 1
                    continue
                problem = parse_kp_bytes(raw, n)
                fingerprints.append(_fingerprint(problem, str(path), _sha(raw)))
                continue
            document = json.loads(gzip.decompress(raw) if path.name.endswith(".json.gz") else raw)
            inspect(document, str(path))
    return {"roots": [str(Path(root).resolve()) for root in roots],
            "include_patterns": ["**/*.kp", "**/*.json", "**/*.json.gz"],
            "excluded_fields": ["candidates", "generations", "summary", "derived_metrics", "outcome tables"],
            "files": files, "fingerprints": fingerprints, "other_dimensions": rejected_dimensions,
            "task_ids": sorted(task_ids),
            "scope": "available_frozen_retained_input_sources_under_declared_roots",
            "unavailable_external_evidence_excluded": True}


def audit_corpus(stage, output, *, source_root=None, historical_roots=None, deadline=None):
    """Require zero exact or item-permuted collisions; never replace a task."""
    ci_only()
    registry, specs, registry_identity = _source_registry(stage)
    output = Path(output)
    cases = []
    for row in specs:
        _deadline(deadline)
        raw = _source_bytes(row, source_root, deadline=deadline)
        problem = parse_kp_bytes(raw, row["n"])
        path = _safe(output, "source/" + row["source_path"], exists=False)
        require(not path.exists(), "Source overwrite refused")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)
        cases.append({**row, "problem": problem, "source_sha256": _sha(raw),
                      "problem_sha256": problem_sha256(problem),
                      "unordered_problem_sha256": unordered_problem_sha256(problem),
                      "source_file": _descriptor(output, path)})
    readme_raw = _source_bytes(registry["readme"], source_root, deadline=deadline)
    require("Creative Commons Attribution 4.0 International License" in readme_raw.decode("utf-8"),
            "Pinned KPLIB README does not contain its registered data-license declaration")
    readme_path = _safe(output, "source/README.md", exists=False)
    readme_path.write_bytes(readme_raw)
    historical = []
    retained = {"files": [], "fingerprints": []}
    if stage in ("main", "technical"):
        rows = registry.get("historical_records")
        require(type(rows) is list and len(rows) == 420, "Main freshness audit needs all 420 historical KPLIB inputs")
        expected = {f"{directory}/n{n:05d}/R01000/s{family:03d}.kp"
                    for _, directory in config.CLASSES for n in (100, 500) for family in range(70)}
        require({row["source_path"] for row in rows} == expected, "Historical freshness inventory is incomplete")
        for row in rows:
            _deadline(deadline)
            raw = _source_bytes(row, source_root, deadline=deadline)
            problem = parse_kp_bytes(raw, row["n"])
            historical.append({**_fingerprint(problem, row["source_path"], _sha(raw)),
                               "bytes": len(raw), "git_blob_sha1": row["git_blob_sha1"]})
        roots = historical_roots if historical_roots is not None else [ROOT / "data/historical_evidence"]
        retained = _retained_historical_inputs(roots)
        require(retained["files"], "No retained historical input scope was inspected")
        new_ids = {row["task_id"] for row in config.task_descriptors("main")}
        require(not (new_ids & set(retained["task_ids"])),
                "A new task identity appears in retained historical input records")
        historical.extend(retained["fingerprints"])
    seen_raw, seen_ordered, seen_permuted = {}, {}, {}
    for row in historical:
        label = row["identity"]
        if row.get("source_sha256"):
            seen_raw.setdefault(row["source_sha256"], label)
        seen_ordered.setdefault(row["problem_sha256"], label)
        seen_permuted.setdefault(row["unordered_problem_sha256"], label)
    internal = set()
    main_paths = {row["source_path"] for row in config.task_descriptors("main")}
    for row in cases:
        label = row["task_id"]
        require(row["unordered_problem_sha256"] not in internal, "Duplicate within the prepared task set: " + label)
        internal.add(row["unordered_problem_sha256"])
        if row["source_path"] in main_paths:
            require(row["source_sha256"] not in seen_raw and row["problem_sha256"] not in seen_ordered and
                    row["unordered_problem_sha256"] not in seen_permuted,
                    "Exact or item-permuted duplicate invalidates task admission: " + label)
        seen_raw[row["source_sha256"]] = label
        seen_ordered[row["problem_sha256"]] = label
        seen_permuted[row["unordered_problem_sha256"]] = label
    return {"schema": "calibrated-selection-source-audit-v1", "stage": stage,
            "status": "AUDITED_PINNED_BYTES_NO_EXACT_OR_PERMUTED_DUPLICATES", "source_commit": config.SOURCE_COMMIT,
            "source_registry_identity": registry_identity, "cases": cases,
            "historical_pinned_fingerprints": historical[:420],
            "retained_historical_scope": retained, "duplicates": [],
            "intentional_technical_reuse": [row["task_id"] for row in config.task_descriptors("technical")]
                                          if stage == "technical" else [],
            "readme": _descriptor(output, readme_path),
            "source_order_preserved": True, "license": "CC-BY-4.0",
            "attribution_url": f"https://github.com/likr/kplib/tree/{config.SOURCE_COMMIT}",
            "freshness_claim": "exact_input_identity_only_not_statistical_independence",
            "search_evaluations": 0}


def _score(problem, mask):
    weight = sum(value for value, bit in zip(problem["weights"], mask, strict=True) if bit == "1")
    profit = sum(value for value, bit in zip(problem["profits"], mask, strict=True) if bit == "1")
    return {"weight": weight, "profit": profit, "feasible": weight <= problem["capacity"]}


def make_bank(problem, preparation_seed, task_index, search_seed):
    ci_only()
    import numpy as np
    from .program.ga_core import create_random_generators
    validate_problem(problem)
    require(all(type(value) is int and value >= 0 for value in (preparation_seed, task_index, search_seed)),
            "Bank seeds and task index must be nonnegative integers")
    entropy = [preparation_seed, task_index, search_seed, 1]
    rng = np.random.Generator(np.random.PCG64(np.random.SeedSequence(entropy)))
    before = deepcopy(rng.bit_generator.state)
    masks = ["0" * problem["n"]]
    masks.extend("".join(str(bit) for bit in rng.integers(0, 2, size=problem["n"]).tolist())
                 for _ in range(BANK_SIZE - 1))
    generators = create_random_generators(search_seed, task_index, 0)
    return {"schema": BANK_SCHEMA, "masks": masks, "scores": [_score(problem, mask) for mask in masks],
            "n": problem["n"], "problem_sha256": problem_sha256(problem),
            "task_index": task_index, "search_seed": search_seed, "preparation_seed": preparation_seed,
            "rng_states": {name: deepcopy(generators[name].bit_generator.state) for name in CHANNELS},
            "preparation_entropy": entropy, "preparation_rng_before": before,
            "preparation_rng_after": deepcopy(rng.bit_generator.state), "bank_size": BANK_SIZE,
            "physical_preparation_evaluations": BANK_SIZE, "search_operator_draws": 0,
            "prefix_rule": "empty_mask_then_random_integer_bits_original_item_order"}


def validate_bank(problem, bank, case=None):
    """Replay preparation draws and independent scalar scores before search."""
    ci_only()
    import numpy as np
    from .program.ga_core import create_random_generators
    validate_problem(problem)
    require(type(bank) is dict and bank.get("schema") == BANK_SCHEMA and bank.get("bank_size") == BANK_SIZE,
            "Wrong bank schema or size")
    require(bank.get("n") == problem["n"] and bank.get("problem_sha256") == problem_sha256(problem),
            "Bank belongs to another problem")
    entropy = [bank["preparation_seed"], bank["task_index"], bank["search_seed"], 1]
    require(all(type(value) is int and value >= 0 for value in entropy), "Invalid bank entropy")
    rng = np.random.Generator(np.random.PCG64(np.random.SeedSequence(entropy)))
    require(bank.get("preparation_entropy") == entropy and bank.get("preparation_rng_before") == rng.bit_generator.state,
            "Wrong bank initial preparation state")
    require(type(bank.get("masks")) is list and type(bank.get("scores")) is list and
            len(bank["masks"]) == len(bank["scores"]) == BANK_SIZE, "Incomplete shared bank")
    for position, (mask, supplied) in enumerate(zip(bank["masks"], bank["scores"], strict=True)):
        expected = "0" * problem["n"] if position == 0 else "".join(
            "1" if value else "0" for value in rng.integers(2, size=problem["n"]))
        require(type(mask) is str and mask == expected, "Bank random prefix changed")
        independent_weight = sum(problem["weights"][i] for i in range(problem["n"]) if mask[i] == "1")
        independent_profit = sum(problem["profits"][i] for i in range(problem["n"]) if mask[i] == "1")
        require(type(supplied) is dict and set(supplied) == {"weight", "profit", "feasible"} and
                type(supplied["weight"]) is int and type(supplied["profit"]) is int and
                type(supplied["feasible"]) is bool and supplied == {"weight": independent_weight,
                    "profit": independent_profit, "feasible": independent_weight <= problem["capacity"]},
                "Independent initial score reconstruction failed")
    require(bank.get("preparation_rng_after") == rng.bit_generator.state and
            bank.get("physical_preparation_evaluations") == BANK_SIZE and bank.get("search_operator_draws") == 0,
            "Bank state/accounting changed")
    states = create_random_generators(bank["search_seed"], bank["task_index"], 0)
    require(bank.get("rng_states") == {name: states[name].bit_generator.state for name in CHANNELS},
            "Six common search states differ from the registered streams")
    if case is not None:
        require(all(bank[key] == case[other] for key, other in
                    (("search_seed", "seed"), ("preparation_seed", "preparation_seed"), ("task_index", "task_index"))),
                "Bank seed/task identity differs from case")
        require(case["initial_parameters"]["target_mu"] <= BANK_SIZE, "Case exceeds shared bank prefix")
    return {"status": "VERIFIED_BANK", "independent_score_checks": BANK_SIZE, "search_evaluations": 0}


def _deadline(deadline):
    require(deadline is None or monotonic() < deadline, "Preparation deadline reached")


def _certificate(problem, *, deadline, memory_limit_bytes):
    require(identity(EXACT_PATH)["sha256"] == EXACT_SHA256, "Pinned independent exact dependency changed")
    from studies.knapsack_parameters.population_size_study.exact import certify_problem
    certificate = certify_problem(problem, deadline=deadline, memory_limit_bytes=memory_limit_bytes)
    require(certificate.get("status") == "CERTIFIED_TWO_INDEPENDENT_EXACT_ORACLES" and
            type(certificate.get("optimum")) is int and certificate["optimum"] > 0, "Exact reference is uncertified")
    certificate["exact_dependency_sha256"] = EXACT_SHA256
    certificate["problem_sha256"] = problem_sha256(problem)
    return certificate


def prepare(stage, output, provenance=None, *, source_root=None, historical_roots=None, seconds=PREPARATION_SECONDS):
    """Freeze sources, two witnesses and each unique twenty-position bank once."""
    ci_only()
    from .common import guard_stage
    guard_stage(stage)
    enclosure = require_enclosure()
    require(stage in ("technical", "main"), "Unknown preparation stage")
    output = Path(output).resolve()
    require(not output.exists() or not any(output.iterdir()), "Existing prepared evidence is never overwritten")
    output.mkdir(parents=True, exist_ok=True)
    started = perf_counter_ns()
    require(type(seconds) is int and 0 < seconds <= PREPARATION_SECONDS, "Invalid preparation time ceiling")
    deadline = monotonic() + seconds
    progress = {"schema": SCHEMA, "stage": stage, "status": "INCOMPLETE", "completed_tasks": 0,
                "search_evaluations": 0, "provenance": deepcopy(provenance)}
    write_json(output / "preparation_progress.json", progress)
    try:
        audit = audit_corpus(stage, output, source_root=source_root,
                             historical_roots=historical_roots, deadline=deadline)
        write_json(output / "source_audit.json", audit)
        cases = config.technical_cases() if stage == "technical" else config.main_cases()
        tasks, banks = [], []
        memory = min(512 * 1024 ** 2, enclosure["kernel_memory_max"] // 2)
        for source in audit["cases"]:
            _deadline(deadline)
            folder = output / "tasks" / source["task_id"]
            folder.mkdir(parents=True)
            problem = source["problem"]
            write_json(folder / "problem.json", problem)
            certification_started = perf_counter_ns()
            certificate = _certificate(problem, deadline=min(deadline, monotonic() + EXACT_CASE_SECONDS),
                                       memory_limit_bytes=memory)
            write_json(folder / "certificate.json", certificate)
            selected = [case for case in cases if case["task_id"] == source["task_id"]]
            for seed in dict.fromkeys(case["seed"] for case in selected):
                case = next(value for value in selected if value["seed"] == seed)
                bank = make_bank(problem, case["preparation_seed"], case["task_index"], seed)
                validation = validate_bank(problem, bank, case)
                path = folder / f"bank-{seed}.json"
                write_json(path, bank)
                banks.append({"task_id": source["task_id"], "seed": seed, "file": _descriptor(output, path),
                              "bank_sha256": _sha(_canonical(bank)), "validation": validation})
            tasks.append({"task_id": source["task_id"], "n": source["n"], "problem_sha256": source["problem_sha256"],
                          "problem": _descriptor(output, folder / "problem.json"),
                          "certificate": _descriptor(output, folder / "certificate.json"),
                          "certification_ns": perf_counter_ns() - certification_started})
            progress["completed_tasks"] = len(tasks)
            write_json(output / "preparation_progress.json", progress)
        manifest = {"schema": SCHEMA, "status": "PREPARED_CERTIFIED", "stage": stage,
                    "source_commit": config.SOURCE_COMMIT, "tasks": tasks, "banks": banks,
                    "case_identities": cases, "source_audit": _descriptor(output, output / "source_audit.json"),
                    "exact_dependency_sha256": EXACT_SHA256, "provenance": deepcopy(provenance),
                    "resource_enclosure": enclosure, "physical_preparation_evaluations": len(banks) * BANK_SIZE,
                    "independent_bank_score_checks": len(banks) * BANK_SIZE,
                    "exact_oracle_solves": 2 * len(tasks), "search_evaluations": 0,
                    "preparation_ns": perf_counter_ns() - started}
        expected_tasks = len(config.task_descriptors(stage)) + (60 if stage == "technical" else 0)
        require(len(tasks) == expected_tasks, "Prepared task set is incomplete")
        write_json(output / "registry.json", manifest)
        progress["status"] = "COMPLETE"
        write_json(output / "preparation_progress.json", progress)
        files = [_descriptor(output, path) for path in sorted(output.rglob("*")) if path.is_file()]
        write_json(output / "file_manifest.json", {"schema": SCHEMA, "files": files})
        return manifest
    except Exception as error:
        progress.update(status="FAILED", error_type=type(error).__name__, error=str(error))
        write_json(output / "preparation_progress.json", progress)
        raise


def _checked(root, descriptor):
    path = _safe(root, descriptor["path"])
    require(identity(path) == {"bytes": descriptor["bytes"], "sha256": descriptor["sha256"]},
            "Prepared file checksum changed")
    return read_json(path)


def load_case(input_root, case):
    """Return only kernel fields and a shared bank; no optimum reaches search."""
    ci_only()
    root = Path(input_root)
    manifest = read_json(root / "registry.json")
    require(manifest.get("schema") == SCHEMA and manifest.get("status") == "PREPARED_CERTIFIED" and
            manifest.get("stage") == case["stage"] and manifest.get("source_commit") == config.SOURCE_COMMIT,
            "Wrong prepared-input identity")
    expected_cases = config.technical_cases() if case["stage"] == "technical" else config.main_cases()
    require(manifest.get("case_identities") == expected_cases and
            manifest.get("exact_dependency_sha256") == EXACT_SHA256,
            "Prepared case rectangle or exact dependency differs")
    audit = _checked(root, manifest["source_audit"])
    require(audit.get("status") == "AUDITED_PINNED_BYTES_NO_EXACT_OR_PERMUTED_DUPLICATES" and
            audit.get("source_commit") == config.SOURCE_COMMIT and audit.get("duplicates") == [] and
            len(audit.get("historical_pinned_fingerprints", [])) == 420,
            "Prepared freshness audit is incomplete")
    require(case in manifest["case_identities"], "Case is absent from prepared identity rectangle")
    tasks = [row for row in manifest["tasks"] if row["task_id"] == case["task_id"]]
    banks = [row for row in manifest["banks"] if row["task_id"] == case["task_id"] and row["seed"] == case["seed"]]
    require(len(tasks) == len(banks) == 1, "Missing or duplicate prepared case")
    problem = _checked(root, tasks[0]["problem"])
    require(problem_sha256(problem) == tasks[0]["problem_sha256"], "Prepared problem semantics changed")
    bank = _checked(root, banks[0]["file"])
    require(_sha(_canonical(bank)) == banks[0]["bank_sha256"], "Prepared bank canonical identity changed")
    validate_bank(problem, bank, case)
    # Reference admission is checked before the search adapter is called; its
    # optimum remains private to preparation and later observation extraction.
    load_reference(root, case["task_id"])
    return problem, bank


def load_reference(input_root, task_id):
    """Read the external reference only after search, for observations."""
    ci_only()
    root = Path(input_root)
    manifest = read_json(root / "registry.json")
    tasks = [row for row in manifest["tasks"] if row["task_id"] == task_id]
    require(len(tasks) == 1, "Reference task is missing or duplicated")
    certificate = _checked(root, tasks[0]["certificate"])
    require(certificate.get("status") == "CERTIFIED_TWO_INDEPENDENT_EXACT_ORACLES" and
            certificate.get("problem_sha256") == tasks[0]["problem_sha256"] and
            certificate.get("exact_dependency_sha256") == EXACT_SHA256, "Wrong exact-reference certificate")
    problem = _checked(root, tasks[0]["problem"])
    optimum = certificate["optimum"]
    require(type(optimum) is int and optimum > 0 and certificate.get("search_uses_optimum") is False,
            "Invalid exact optimum or search-reference separation")
    methods = {"capacity_certificate": "capacity_max_profit_dp_packed_witness",
               "profit_certificate": "profit_min_weight_dp_independent_packed_witness"}
    for name, method in methods.items():
        witness = certificate[name]
        require(witness.get("method") == method and witness.get("arithmetic") == "exact_int64",
                "Two independent exact methods are required")
        require(type(witness["witness_mask"]) is str and len(witness["witness_mask"]) == problem["n"] and
                set(witness["witness_mask"]) <= {"0", "1"}, "Malformed exact witness")
        score = _score(problem, witness["witness_mask"])
        require(score["feasible"] and score["profit"] == optimum == witness["optimum_profit"] and
                score["weight"] == witness["witness_weight"], "External exact witness is invalid")
    return optimum


