function contract = usa001_contract()
%USA001_CONTRACT Published milestone contract used as the staged example.
% Qualification can only fail decisively or proceed. Only the terminal
% full-verification stage is allowed to produce PASS_FULL.

gateTemplate = struct( ...
    "id", "", ...
    "kind", "", ...
    "generation", 0, ...
    "target", 0, ...
    "tolerance", 0, ...
    "toleranceMode", "", ...
    "required", true, ...
    "irreversibleAtCheckpoint", false);

gates = repmat(gateTemplate, 4, 1);
gates(1) = make_gate("P1", "perfect_fraction", 1000, ...
    0.9, 0.05, "relative", true);
gates(2) = make_gate("P2", "perfect_fraction", 2000, ...
    1.0, 0.05, "relative", true);
gates(3) = make_gate("P3", "median_reported_iteration", 100000, ...
    1000, 0.05, "relative", false);
gates(4) = make_gate("P4", "max_absolute_objective", 100000, ...
    0, 1e-12, "absolute", false);

contract = struct();
contract.schemaVersion = 1;
contract.id = "USA-001_FAST_FAIL_CLOSED_V1";
contract.candidateId = "USA-001";
contract.runIds = (1:10).';
seedTemplate = struct("instanceSeed", uint32(0), ...
    "populationSeed", uint32(0), "algorithmSeed", uint32(0), ...
    "analysisSeed", uint32(0));
contract.seedLedger = repmat(seedTemplate, 10, 1);
for run = 1:10
    contract.seedLedger(run) = struct( ...
        "instanceSeed", uint32(202204500 + run), ...
        "populationSeed", uint32(202214500 + run), ...
        "algorithmSeed", uint32(202224500 + run), ...
        "analysisSeed", uint32(202234500));
end
contract.maximumGeneration = 100000;
contract.minimumObjective = 0;
contract.perfectObjectiveTolerance = 1e-12;
contract.gates = gates;
contract.adapterIdentity = struct();
contract.provenance = struct( ...
    "sourceRevision", ...
        "2c33060320f722e6bb737b607cf0b27a9aa4256c", ...
    "publishedTargetSHA256", ...
        "710feb1ae22f2c7baf27ac0092b60662ac49cae53f59f3ddf2a92ecff08bad37", ...
    "instanceSpecSHA256", ...
        "ae6c4d2283db1ca44c2c31d31699b53f262617e0f5b34e87651beddb0387cb7d", ...
    "implementationSHA256", ...
        "76b72209a5acf06ab5f59fe43bec4cba8b52264afa4d9f4d27d40e5491575eba");
end

function gate = make_gate(id, kind, generation, target, tolerance, mode, irreversible)
gate = struct( ...
    "id", string(id), ...
    "kind", string(kind), ...
    "generation", double(generation), ...
    "target", double(target), ...
    "tolerance", double(tolerance), ...
    "toleranceMode", string(mode), ...
    "required", true, ...
    "irreversibleAtCheckpoint", logical(irreversible));
end
